"""Deterministic decision rules D1–D8 of the "Decisões" chapter (spec §4.5 "Decision rules").

Each row (``Decision`` in ``frontend/src/types/story.ts``):
{code, decision, short, evidence, impact, impact_basis: "horizonte" | "backtest_anualizado", owner,
link: {label, route}}. All rules are evaluated, sorted by impact descending, at most one per code,
top ``MAX_DECISIONS``. Impacts are never summed (they overlap: the target gap contains part of the
budget gap). Backtest-window impacts are annualised to the horizon (× h / |BT months|) so the rows sort
on a comparable scale. No number here is generated by AI: every input comes from the deviation engine,
``assess`` or ``fva_report`` (computed once by the builder and handed over in ``facts``).
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

import pandas as pd

from app.deviations import common, forecast_error, rootcause
from app.forecasting.panel import SERIES_SEP
from app.services.context import PlanningContext

from . import templates as T

MAX_DECISIONS = 5
DECISION_CODES = ("D1", "D2", "D3", "D4", "D5", "D6", "D7", "D8")
IMPACT_BASIS = ("horizonte", "backtest_anualizado")

# Rule thresholds (spec §4.5 "Decision rules").
D1_MIN_SHARE_OF_P = 0.01  # |V| of the members tagged "premissa otimista" ≥ 1% of the node budget
D2_MIN_PROMO_SHARE = 0.15  # promoção + merchandising ≥ 15% of the forecast error
D3_MIN_UPSIDE_SHARE = 0.005  # Σ V⁺ of the favourable members ≥ 0,5% of the node budget
D6_MAX_FVA_PP = -0.02  # an event type whose adjustments worsened WMAPE by ≥ 2 p.p. ...
D6_MIN_OVERRIDES = 10  # ... over at least 10 adjustments
D7_MIN_SHARE_OF_P = 0.01  # |price effect| ≥ 1% of the node budget (and negative)
MAX_NAMES = 3

FVA_ROUTE = rootcause.FVA_ROUTE
FVA_LINK_LABEL = "Ver valor dos ajustes"


def _row(
    code: str,
    decision: str,
    short: str,
    evidence: str,
    impact: float,
    basis: str,
    owner: str,
    link_label: str,
    route: str,
) -> dict[str, Any]:
    return {
        "code": code,
        "decision": decision,
        "short": short,
        "evidence": evidence,
        "impact": float(abs(impact)),
        "impact_basis": basis,
        "owner": owner,
        "link": {"label": link_label, "route": route},
    }


def _names(labels: list[str], level: str) -> str:
    """'A, B e C' or 'A, B, C e mais 2 clientes'."""
    if len(labels) <= MAX_NAMES:
        return T.join_names(labels)
    rest = len(labels) - MAX_NAMES
    return f"{', '.join(labels[:MAX_NAMES])} e mais {rest} {T.level_word(level, rest)}"


def _desvios(facts: Mapping[str, Any], **state: Any) -> str:
    return T.deviations_href({**state, "path": facts.get("scope_path") or {}})


def _d1(facts: Mapping[str, Any]) -> dict[str, Any] | None:
    rows, p_node, level = facts.get("gap_rows") or [], abs(facts.get("p_node") or 0.0), facts["level"]
    hits = [
        r
        for r in rows
        if any(t.get("code") == "premissa_otimista" for t in r.get("tags") or [])
        and abs(r["variance"]) >= D1_MIN_SHARE_OF_P * p_node
    ]
    if not hits or p_node <= 0:
        return None
    hits.sort(key=lambda r: r["variance"])
    top = hits[0]
    evidence = f"{top['label']}: orçamento supõe {T.P1s(top.get('growth_plan'))} de crescimento"
    if T.num(top.get("growth_fc")) is not None:
        evidence += f" vs {T.P1s(top['growth_fc'])} previstos"
    rv = T.num(top.get("realized_variance_pct"))
    if rv is not None and rv <= -T.RECURRENT_VPCT:
        evidence += f", e já ficou {T.P1s(rv)} vs orçamento nos últimos 12 meses"
    n = len(hits)
    names = _names([r["label"] for r in hits], level)
    return _row(
        "D1",
        f"Revisar o orçamento de {names}",
        f"revisar o orçamento de {n} {T.level_word(level, n)}",
        evidence,
        sum(r["variance"] for r in hits),
        "horizonte",
        "Key Account + FP&A",
        T.LINK_LABEL,
        _desvios(facts, cmp="fc_pl", nivel=level),
    )


def _d2(facts: Mapping[str, Any]) -> dict[str, Any] | None:
    causes = facts.get("causes") or []
    picked = [c for c in causes if c.get("code") in ("promocao", "merchandising")]
    share = sum(float(c.get("share") or 0.0) for c in picked)
    if not picked or share < D2_MIN_PROMO_SHARE:
        return None
    ae = sum(float(c.get("abs_error") or 0.0) for c in picked)
    return _row(
        "D2",
        "Cadastrar o calendário promocional como ajuste comercial antes do consenso",
        "cadastrar o calendário promocional",
        f"{T.P0(share)} do erro veio de promoções/merchandising não antecipados",
        ae * facts["annualise"],
        "backtest_anualizado",
        "Trade Marketing + Demanda",
        T.LINK_LABEL,
        _desvios(facts, cmp="ac_fc", nivel=facts["level"], causa="promocao"),
    )


def _d3(facts: Mapping[str, Any]) -> dict[str, Any] | None:
    rows, p_node, level = facts.get("gap_rows") or [], abs(facts.get("p_node") or 0.0), facts["level"]
    fav = sorted((r for r in rows if r["variance"] > 0), key=lambda r: -r["variance"])
    up = sum(r["variance"] for r in fav)
    if not fav or p_node <= 0 or up < D3_MIN_UPSIDE_SHARE * p_node:
        return None
    n = len(fav)
    return _row(
        "D3",
        f"Garantir abastecimento para a demanda adicional de {_names([r['label'] for r in fav], level)}",
        "garantir abastecimento para a demanda adicional",
        f"{n} {T.level_word(level, n)} acima do orçamento",
        up,
        "horizonte",
        "Supply + Key Account",
        T.LINK_LABEL,
        _desvios(facts, cmp="fc_pl", nivel=level),
    )


def _d4_d8(facts: Mapping[str, Any]) -> dict[str, Any] | None:
    a = facts.get("assess") or {}
    if not a.get("available"):
        return None
    cls, prob = a.get("classification"), T.num(a.get("probability"))
    gap = (T.num(a.get("target")) or 0.0) - (T.num(a.get("consensus")) or 0.0)
    evidence = f"{T.P0(prob)} de chance de bater a meta"
    if cls in ("STRETCH", "AGGRESSIVE"):
        route = facts.get("simulate_route") or _desvios(facts, cmp="fc_tg", nivel=facts.get("meta_level"))
        label = T.SIMULATE_LABEL if facts.get("simulate_route") else T.LINK_LABEL
        return _row(
            "D4",
            f"Decidir: recalibrar a meta ou aprovar {facts.get('lever_text') or T.lever_text(None, None)}",
            "decidir sobre a meta",
            evidence,
            gap,
            "horizonte",
            "Diretoria Comercial",
            label,
            route,
        )
    if cls == "UNDERESTIMATED":
        return _row(
            "D8",
            "Elevar a meta: o consenso já a supera",
            "elevar a meta",
            evidence,
            gap,
            "horizonte",
            "Diretoria Comercial",
            T.LINK_LABEL,
            _desvios(facts, cmp="fc_tg"),
        )
    return None


def _d5(ctx: PlanningContext, facts: Mapping[str, Any]) -> dict[str, Any] | None:
    """Series whose forecast is persistently biased: |tracking signal| ≥ 4,5 or |bias| ≥ 15% (backtest)."""
    ids, months = facts.get("ids"), common.backtest_months(ctx)
    if ids is None or not len(months):
        return None
    cells = forecast_error.error_cells(ctx, "ac_fc", pd.Index(ids), months)
    if cells.empty:
        return None
    g = cells.assign(abs_e=cells["e"].abs()).groupby("series_id")
    t = g[["abs_e", "e", "actual"]].sum()
    t["ts"] = g["ts"].first()
    a = t["actual"].where(t["actual"] > 0)
    t["bias"] = t["e"] / a
    t["wmape"] = t["abs_e"] / a
    flagged = t[(t["ts"].abs() >= rootcause.TS_LIMIT) | (t["bias"].abs() >= rootcause.HIGH_BIAS)]
    if flagged.empty:
        return None
    rev = facts.get("series_revenue")
    rev = rev.reindex(flagged.index).fillna(0.0) if rev is not None else pd.Series(0.0, index=flagged.index)
    impact = float((flagged["wmape"].fillna(0.0) * rev).sum())
    n = len(flagged)
    return _row(
        "D5",
        f"Corrigir o viés de {n} {T.plural(n, 'série', 'séries')}",
        f"corrigir o viés de {n} {T.plural(n, 'série', 'séries')}",
        "Sinal de rastreamento ou viés fora do limite no backtest",
        impact,
        "horizonte",
        "Planejamento de Demanda",
        T.LINK_LABEL,
        _desvios(facts, cmp="ac_fc", nivel="series"),
    )


def _d6(ctx: PlanningContext, facts: Mapping[str, Any]) -> dict[str, Any] | None:
    """The event type whose historical adjustments worsened accuracy the most (FVA ≤ −2 p.p., ≥ 10 adjustments)."""
    fva = facts.get("fva") or {}
    groups = [
        g
        for g in fva.get("by_event_type") or []
        if T.num(g.get("fva_pp")) is not None
        and g["fva_pp"] <= D6_MAX_FVA_PP
        and int(g.get("overrides") or 0) >= D6_MIN_OVERRIDES
    ]
    if not groups:
        return None
    worst = min(groups, key=lambda g: g["fva_pp"])
    event = str(worst["event_type"])
    detail = pd.DataFrame(fva.get("overrides") or [])
    impact = 0.0
    if not detail.empty and {"customer", "sku", "date", "error_consensus", "error_statistical"} <= set(detail.columns):
        d = detail[detail["event_type"] == event].copy()
        d["series_id"] = d["customer"].astype(str) + SERIES_SEP + d["sku"].astype(str)
        d["date"] = pd.to_datetime(d["date"])
        cells = forecast_error.error_cells(ctx, "ac_fc", pd.Index(d["series_id"].unique()), common.backtest_months(ctx))
        price = cells.set_index(["series_id", "date"])["p"] if not cells.empty else pd.Series(dtype=float)
        p = pd.Series([price.get((s, dt), 0.0) for s, dt in zip(d["series_id"], d["date"], strict=True)], index=d.index)
        impact = float(((d["error_consensus"] - d["error_statistical"]) * p).sum()) * facts["annualise"]
    n = int(worst.get("overrides") or 0)
    word = T.lower_first(event)
    return _row(
        "D6",
        f"Rever a regra de ajustes de {word}",
        f"rever os ajustes de {word}",
        f"Pioraram a acurácia em {T.PP(abs(worst['fva_pp']))} ({n} {T.plural(n, 'ajuste', 'ajustes')})",
        impact,
        "backtest_anualizado",
        "Planejamento + Comercial",
        FVA_LINK_LABEL,
        FVA_ROUTE,
    )


def _d7(facts: Mapping[str, Any]) -> dict[str, Any] | None:
    price, p_node = T.num(facts.get("price_effect")), abs(facts.get("p_node") or 0.0)
    if price is None or price >= 0 or p_node <= 0 or abs(price) < D7_MIN_SHARE_OF_P * p_node:
        return None
    prem, reg = T.num(facts.get("plan_price_premium")), T.num(facts.get("reg_price_gap"))
    evidence = f"Orçamento assume preço {T.P1s(prem)} vs o praticado" if prem is not None else "Preço abaixo do orçado"
    if reg is not None:
        evidence += f"; no último ano o preço realizado ficou {T.P1s(reg)} vs o orçado"
    level = "category" if not (facts.get("scope_path") or {}).get("category") else facts["level"]
    return _row(
        "D7",
        "Revisar a premissa de preço do orçamento",
        "revisar a premissa de preço",
        evidence,
        price,
        "horizonte",
        "FP&A + Pricing",
        T.LINK_LABEL,
        _desvios(facts, cmp="fc_pl", nivel=level),
    )


def build_decisions(ctx: PlanningContext, filters: dict[str, Any], facts: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Decision rows for the report scope, sorted by impact (top ``MAX_DECISIONS``, one per code).

    ``facts`` carries the inputs the builder already computed: level, scope_path, gap_rows, p_node,
    price_effect, plan_price_premium, reg_price_gap, causes, assess, lever_text, simulate_route,
    meta_level, fva, ids, series_revenue and annualise (= h / |BT months|)."""
    rows = [
        _d1(facts),
        _d2(facts),
        _d3(facts),
        _d4_d8(facts),
        _d5(ctx, facts),
        _d6(ctx, facts),
        _d7(facts),
    ]
    out = [r for r in rows if r is not None and r["impact"] > 0]
    out.sort(key=lambda r: (-r["impact"], r["code"]))
    return out[:MAX_DECISIONS]
